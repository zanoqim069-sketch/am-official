@app.route('/register',methods=['GET','POST'])
def register():
    if request.method=='POST':
        email=request.form.get('email','').strip().lower()
        name=request.form.get('name','').strip()
        password=request.form.get('password','')
        if not name or '@' not in email or len(password)<10:
            flash('Inserisci dati validi e una password di almeno 10 caratteri.')
            return redirect(url_for('register'))
        from psycopg.errors import UniqueViolation
        try:
            with db() as c:
                c.execute('INSERT INTO users(email,password,name) VALUES(%s,%s,%s)',(email,generate_password_hash(password),name))
        except UniqueViolation:
            flash('Email già registrata.')
            return redirect(url_for('register'))
        flash('Registrazione completata. Accedi al tuo account.')
        return redirect(url_for('login'))
    return render_template('auth.html',mode='register')

@app.route('/login',methods=['GET','POST'])
def login():
    if request.method=='POST':
        with db() as c:
            u=c.execute('SELECT * FROM users WHERE email=%s',(request.form.get('email','').strip().lower(),)).fetchone()
        if u and check_password_hash(u['password'],request.form.get('password','')):
            session.clear()
            session.update(uid=u['id'],name=u['name'],role=u['role'])
            return redirect(url_for('admin') if u['role']=='admin' else url_for('account'))
        flash('Credenziali non valide.')
    return render_template('auth.html',mode='login')

@app.route('/logout',methods=['POST'])
@login_required
def logout():
    session.clear()
    return redirect(url_for('home'))

@app.route('/account')
@login_required
def account():
    with db() as c:
        orders=c.execute('SELECT o.*,p.title FROM orders o JOIN products p ON p.id=o.product_id WHERE o.user_id=%s ORDER BY o.id DESC',(session['uid'],)).fetchall()
        subs=c.execute('SELECT s.*,t.title FROM submissions s JOIN tasks t ON t.id=s.task_id WHERE s.user_id=%s ORDER BY s.id DESC',(session['uid'],)).fetchall()
    return render_template('account.html',orders=orders,subs=subs)

@app.route('/orders/create/<int:pid>',methods=['POST'])
@login_required
def order_create(pid):
    with db() as c:
        p=c.execute('SELECT * FROM products WHERE id=%s AND active=1',(pid,)).fetchone()
        if not p or p['stock']<1: abort(404)
        c.execute('INSERT INTO orders(user_id,product_id,quantity,unit_price,created_at) VALUES(%s,%s,%s,%s,%s)',(session['uid'],pid,1,p['price'],datetime.now(timezone.utc).isoformat()))
    flash('Richiesta d’ordine registrata. Nessun pagamento è stato addebitato.')
    return redirect(url_for('account'))

@app.route('/tasks/submit/<int:tid>',methods=['POST'])
@login_required
def task_submit(tid):
    note=request.form.get('note','').strip()
    if not 10 <= len(note) <= 2000:
        flash('Inserisci una descrizione tra 10 e 2000 caratteri.')
        return redirect(url_for('tasks'))
    with db() as c:
        t=c.execute('SELECT id FROM tasks WHERE id=%s AND active=1',(tid,)).fetchone()
        if not t: abort(404)
        c.execute('INSERT INTO submissions(user_id,task_id,note,created_at) VALUES(%s,%s,%s,%s)',(session['uid'],tid,note,datetime.now(timezone.utc).isoformat()))
    flash('Attività inviata per revisione.')
    return redirect(url_for('account'))

@app.route('/admin')
@admin_required
def admin():
    with db() as c:
        users=c.execute('SELECT id,email,name,role FROM users ORDER BY id DESC').fetchall()
        products=c.execute('SELECT * FROM products ORDER BY id DESC').fetchall()
        tasks=c.execute('SELECT * FROM tasks ORDER BY id DESC').fetchall()
        orders=c.execute('SELECT o.*,u.email,p.title FROM orders o JOIN users u ON u.id=o.user_id JOIN products p ON p.id=o.product_id ORDER BY o.id DESC').fetchall()
        subs=c.execute('SELECT s.*,u.email,t.title FROM submissions s JOIN users u ON u.id=s.user_id JOIN tasks t ON t.id=s.task_id ORDER BY s.id DESC').fetchall()
    return render_template('admin.html',users=users,products=products,tasks=tasks,orders=orders,subs=subs)

@app.route('/admin/products',methods=['POST'])
@admin_required
def add_product():
    try: price=float(request.form['price']);stock=int(request.form['stock'])
    except (ValueError,KeyError): abort(400)
    if price<0 or stock<0: abort(400)
    with db() as c:
        c.execute('INSERT INTO products(title,description,price,stock) VALUES(%s,%s,%s,%s)',(request.form['title'][:150],request.form['description'][:2000],price,stock))
    return redirect(url_for('admin'))

